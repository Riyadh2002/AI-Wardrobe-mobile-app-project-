from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

class OutfitItemRef(BaseModel):
    """Reference to an individual wardrobe piece used in an outfit."""
    id: str = Field(..., description="Unique ID of the item.")
    name: str = Field(..., description="Item display name.")
    category: str = Field(..., description="Tops, Bottoms, Dresses, Shoes, Accessories, etc.")
    imageUrl: str = Field(..., description="Image URL of the garment.")
    color: Optional[str] = Field(None, description="Garment color.")

class OutfitGenerateRequest(BaseModel):
    """Request payload to synthesize a personalized outfit."""
    occasion: str = Field("Casual", description="Casual, Office, Date, Party, Wedding, Travel, Workout.")
    style: str = Field("Minimal", description="Minimal, Casual, Streetwear, Formal, Smart Casual, Vintage.")
    color_preference: Optional[str] = Field("Neutral", description="Neutral, Dark, Bright, Pastel.")
    temperature: Optional[str] = Field("24°C", description="Current or target ambient temperature.")
    weather_condition: Optional[str] = Field("Sunny", description="e.g. Rainy, Sunny, Chilly, Snow.")
    custom_prompt: Optional[str] = Field(None, description="Freeform instruction, e.g. 'Must include my navy blazer'.")
    wardrobe_items: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Optional list of current user wardrobe items to select from."
    )

class OutfitGenerateResponse(BaseModel):
    """Curated outfit generated by the AI agent."""
    id: str = Field(..., description="Generated unique outfit ID.")
    name: str = Field(..., description="Editorial outfit title.")
    occasion: str = Field(..., description="Occasion tag.")
    style: str = Field(..., description="Style classification.")
    confidence_score: int = Field(96, description="AI stylist match rating out of 100.")
    items: List[OutfitItemRef] = Field(..., description="List of garment pieces assembled in this look.")
    explanation: str = Field(..., description="High-fashion 'Why this works' explanation.")
    styling_tips: List[str] = Field(default_factory=list, description="Actionable styling tips.")
    is_ai_generated: bool = Field(True, description="True if generated by live Gemini.")
    notice: Optional[str] = Field(None, description="Developer notice if running in mock/fallback mode.")
