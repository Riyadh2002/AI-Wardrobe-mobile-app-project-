from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from .outfit import OutfitGenerateResponse

class ChatMessage(BaseModel):
    """Single chat turn in the conversation."""
    id: str
    sender: str = Field(..., description="'user' or 'stylist'")
    text: str
    timestamp: Optional[str] = None

class StylistChatRequest(BaseModel):
    """Request payload for conversational AI Stylist."""
    message: str = Field(..., description="User's prompt or question.")
    history: Optional[List[ChatMessage]] = Field(default_factory=list, description="Recent conversation turns.")
    user_style_preference: Optional[str] = Field("Minimal, Streetwear", description="Known user style preferences.")
    user_wardrobe_summary: Optional[str] = Field(None, description="Summary of user closet inventory.")

class StylistChatResponse(BaseModel):
    """AI Stylist response with advice, optional outfit attachment, and followup chips."""
    message: str = Field(..., description="Conversational styling advice from the agent.")
    outfit_suggestion: Optional[OutfitGenerateResponse] = Field(None, description="Optional outfit recommended by agent.")
    suggested_prompts: List[str] = Field(default_factory=list, description="Followup question chips for user convenience.")
    is_ai_generated: bool = Field(True, description="True if generated by live Gemini.")
    notice: Optional[str] = Field(None, description="Developer notice if fallback mode.")
