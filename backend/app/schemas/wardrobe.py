from typing import List, Optional
from pydantic import BaseModel, Field

class AutoTagRequest(BaseModel):
    """Request payload for vision auto-tagging."""
    image_url: Optional[str] = Field(None, description="Public HTTP/HTTPS URL of the clothing image.")
    image_base64: Optional[str] = Field(None, description="Base64 encoded image string (with or without data URI header).")
    hint: Optional[str] = Field(None, description="Optional user clue (e.g., 'vintage leather jacket').")

class AutoTagResponse(BaseModel):
    """Structured AI output describing garment attributes."""
    name: str = Field(..., description="Suggested editorial product title.")
    category: str = Field(..., description="Tops, Bottoms, Dresses, Shoes, Accessories, or Outerwear.")
    color: str = Field(..., description="Primary color name, e.g., 'Off-White', 'Charcoal', 'Navy'.")
    colorHex: str = Field("#18181B", description="Matching 6-digit hex color code, e.g. '#1E3A8A'.")
    style: str = Field("Minimal", description="Style taxonomy: Minimal, Casual, Streetwear, Formal, Smart Casual, Vintage.")
    season: str = Field("All Year", description="Season suitability: Summer, Fall, Winter, Spring, All Year.")
    brand: Optional[str] = Field(None, description="Detected or suggested brand aesthetic.")
    pattern: Optional[str] = Field("Solid", description="Pattern: Solid, Striped, Plaid, Floral, Graphic, etc.")
    material: Optional[str] = Field(None, description="Estimated fabric/material: Cotton, Wool, Linen, Silk, Leather, Denim.")
    confidence: float = Field(0.95, description="Confidence score between 0.0 and 1.0.")
    styling_tips: List[str] = Field(default_factory=list, description="Editorial pairing notes.")
    is_ai_generated: bool = Field(True, description="True if generated by live Gemini; False if fallback.")
    notice: Optional[str] = Field(None, description="Helpful developer status notice.")
